# Assignment Operators Practice

number = float(input("Enter a number: "))

print("\nOriginal Value =", number)

# += Operator
number += 10
print("After += 10 :", number)

# -= Operator
number -= 5
print("After -= 5  :", number)

# *= Operator
number *= 2
print("After *= 2  :", number)

# /= Operator
number /= 4
print("After /= 4  :", number)