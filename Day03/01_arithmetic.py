# Arithmetic
# Add two numbers
num1 = float(input("Enter 1st number :"))
num2 = float(input("Enter 2nd number :"))
result = num1 + num2
print(f'The sum of these two numbers is = {result:.2f}')
print()

# Multiply two numbers
product = num1*num2
print(f'The product of two numbers is = {product:.2f}')
print()

# Area of triangle
base = float(input("Enter base: "))
height = float(input("Enter height: "))

area = (base * height) / 2
print(f'Area of the triangle is = {area:.2f}')
print()

# Square of a number
number = float(input('Enter a  number: '))
Square = number**2
print(f'The Square of {number:.2f} is {Square:.2f}')
print()

# Cube of a number
Cube = number**3
print(f'The Cube of {number:.2f} is {Cube:.2f}')
