# Comparison Operators Practice

num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))

print("\nComparison Results")

# Equal to (==)
print(f"{num1} == {num2} :", num1 == num2)

# Not Equal to (!=)
print(f"{num1} != {num2} :", num1 != num2)

# Greater than (>)
print(f"{num1} > {num2} :", num1 > num2)

# Less than (<)
print(f"{num1} < {num2} :", num1 < num2)

# Greater than or Equal to (>=)
print(f"{num1} >= {num2} :", num1 >= num2)

# Less than or Equal to (<=)
print(f"{num1} <= {num2} :", num1 <= num2)