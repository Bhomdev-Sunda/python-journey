# Escape Sequences in Python
print("========== ESCAPE SEQUENCES ==========\n")

# New Line (\n)
print("1. New Line (\\n)")
print("Python\nProgramming")

# Tab (\t)
print("\n2. Tab (\\t)")
print("Name\tAge\tCity")
print("Bhomdev\t22\tPatiala")

# Backslash (\\)
print("\n3. Backslash (\\\\)")
print("C:\\Users\\Bhomdev\\Documents")

# Single Quote (\')
print("\n4. Single Quote (\\')")
print('It\'s a beautiful day.')

# Double Quote (\")
print("\n5. Double Quote (\\\")")
print("He said, \"Welcome to Python!\"")

# Backspace (\b)
print("\n6. Backspace (\\b)")
print("Pythonn\b")

# Carriage Return (\r)
print("\n7. Carriage Return (\\r)")
print("Hello\rPython")

# Form Feed (\f)
print("\n8. Form Feed (\\f)")
print("Python\fProgramming")

# Vertical Tab (\v)
print("\n9. Vertical Tab (\\v)")
print("Python\vProgramming")

# ASCII Bell (\a)
print("\n10. Alert/Bell (\\a)")
print("Python\a")

# Unicode Character (\u)
print("\n11. Unicode (\\u)")
print("\u2764")      # ❤
print("\u2705")      # ✅
print("\u2605")      # ★

# Raw String (r)
print("\n12. Raw String")
print(r"C:\Users\Bhomdev\Documents")
print("\n========== END ==========")